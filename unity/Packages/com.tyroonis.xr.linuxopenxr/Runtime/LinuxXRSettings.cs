using System.IO;
using UnityEngine;
using UnityEngine.XR.Management;

namespace Tyroonis.XR.LinuxXR
{
    public enum LinuxXRRuntime
    {
        [InspectorName("Automatic (prefer WiVRn)")] Auto,
        WiVRn,
        Monado,
        [InspectorName("Active runtime (active_runtime.json)")] ActiveRuntime,
        [InspectorName("Custom manifest path")] Custom
    }

    public enum LinuxXRTrackingOrigin
    {
        [InspectorName("Floor")] Floor,
        [InspectorName("Device (head)")] Device
    }

    public enum LinuxXRStereoMode
    {
        [InspectorName("Single Pass Instanced (recommended)")] SinglePassInstanced,
        [InspectorName("Multi Pass")] MultiPass
    }

    public enum LinuxXRMirrorMode
    {
        [InspectorName("Left eye")] LeftEye = 0,
        [InspectorName("Right eye")] RightEye = 1,
        [InspectorName("Both eyes")] SideBySide = 2,
        [InspectorName("Off")] None = 3
    }

    /// <summary>
    /// Settings under Project Settings → XR Plug-in Management → LinuxXR.
    /// They are passed to the native plugin when XR starts and are also written to
    /// Library/LinuxXR/settings.txt (read by the plugin when it loads, before C# runs).
    /// </summary>
    [XRConfigurationData("LinuxXR", "Tyroonis.XR.LinuxXR.Settings")]
    public class LinuxXRSettings : ScriptableObject
    {
        public const string SettingsFile = "Library/LinuxXR/settings.txt";

        [Tooltip("OpenXR runtime used in Play Mode. Changes apply the next time you press Play.")]
        public LinuxXRRuntime runtime = LinuxXRRuntime.Auto;

        [Tooltip("Path to an OpenXR runtime manifest (*.json), only used with 'Custom manifest path'.")]
        public string customRuntimeManifest = "";

        public LinuxXRTrackingOrigin trackingOrigin = LinuxXRTrackingOrigin.Floor;

        public LinuxXRStereoMode stereoMode = LinuxXRStereoMode.SinglePassInstanced;

        [Tooltip("What the Game View shows in Play Mode.")]
        public LinuxXRMirrorMode mirrorMode = LinuxXRMirrorMode.LeftEye;

        [Range(0.5f, 1.5f), Tooltip("Render resolution relative to the runtime's recommendation. Lower it (e.g. 0.7) if the headset stutters.")]
        public float renderScale = 1.0f;

        [Tooltip("Verbose native log (debug messages in the Console and in linuxxr.log).")]
        public bool verboseLogging = false;

        [Tooltip("Show native [LinuxXR] messages in the Unity Console (otherwise only in Editor.log and linuxxr.log).")]
        public bool forwardLogToConsole = true;

#if !UNITY_EDITOR
        static LinuxXRSettings s_RuntimeInstance;
        void Awake() { s_RuntimeInstance = this; }
#endif

        public string RuntimeString
        {
            get
            {
                switch (runtime)
                {
                    case LinuxXRRuntime.WiVRn: return "wivrn";
                    case LinuxXRRuntime.Monado: return "monado";
                    case LinuxXRRuntime.ActiveRuntime: return "active";
                    case LinuxXRRuntime.Custom:
                        return string.IsNullOrWhiteSpace(customRuntimeManifest) ? "auto" : customRuntimeManifest.Trim();
                    default: return "auto";
                }
            }
        }

        /// <summary>Writes the values the native plugin needs to Library/LinuxXR/settings.txt.</summary>
        public void WriteNativeSettingsFile()
        {
            try
            {
                Directory.CreateDirectory(Path.GetDirectoryName(SettingsFile));
                File.WriteAllText(SettingsFile,
                    "# Generated by LinuxXRSettings - do not edit\n" +
                    $"runtime={RuntimeString}\n" +
                    $"origin={(trackingOrigin == LinuxXRTrackingOrigin.Floor ? "floor" : "device")}\n" +
                    $"singlePass={(stereoMode == LinuxXRStereoMode.SinglePassInstanced ? 1 : 0)}\n" +
                    $"mirrorMode={(int)mirrorMode}\n" +
                    $"renderScale={renderScale.ToString(System.Globalization.CultureInfo.InvariantCulture)}\n" +
                    $"verboseLog={(verboseLogging ? 1 : 0)}\n");
            }
            catch (IOException e)
            {
                Debug.LogWarning("[LinuxXR] Could not write " + SettingsFile + ": " + e.Message);
            }
        }

        /// <summary>Passes the settings to the loaded native library.</summary>
        public void ApplyToNative()
        {
            if (!LinuxXRNative.IsAvailable) return;
            LinuxXRNative.SetSettings(RuntimeString, trackingOrigin == LinuxXRTrackingOrigin.Floor,
                stereoMode == LinuxXRStereoMode.SinglePassInstanced, (int)mirrorMode, renderScale, verboseLogging);
        }

        void OnValidate()
        {
            WriteNativeSettingsFile();
        }

        public static LinuxXRSettings GetSettings()
        {
            LinuxXRSettings settings = null;
#if UNITY_EDITOR
            UnityEditor.EditorBuildSettings.TryGetConfigObject("Tyroonis.XR.LinuxXR.Settings", out settings);
#else
            settings = s_RuntimeInstance;
#endif
            return settings;
        }
    }
}
